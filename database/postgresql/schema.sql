CREATE TABLE categoria (
    idcategoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria varchar(70) NOT NULL
);

CREATE TABLE cliente (
    idcliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    apellido varchar(100) NOT NULL,
    correo varchar(120),
    zipcode varchar(50),
    fecha_nacimiento date NOT NULL,
    contrasena varchar(100) NOT NULL,
    genero varchar(20) NOT NULL,
    imagen_usuario varchar(100)
);

CREATE TABLE genero (
    idgenero integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(40) NOT NULL
);

CREATE TABLE subcategoria (
    idsubcategoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_subcategoria varchar(70),
    idcategoria integer,
    CONSTRAINT subcategoria_categoria_fk FOREIGN KEY (idcategoria) REFERENCES categoria (idcategoria) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_subcategoria_idcategoria ON subcategoria (idcategoria);

CREATE TABLE subsub (
    idsubsub integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_subsub varchar(70),
    idsubcategoria integer,
    CONSTRAINT subsub_subcategoria_fk FOREIGN KEY (idsubcategoria) REFERENCES subcategoria (idsubcategoria) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_subsub_idsubcategoria ON subsub (idsubcategoria);

CREATE TABLE producto (
    idproducto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto varchar(250) NOT NULL,
    descripcion varchar(500),
    precio decimal(10,2) NOT NULL,
    idsubsub integer,
    idgenero integer,
    imagen_nombre varchar(255),
    CONSTRAINT producto_genero_fk FOREIGN KEY (idgenero) REFERENCES genero (idgenero) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT producto_subsub_fk FOREIGN KEY (idsubsub) REFERENCES subsub (idsubsub) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_producto_idgenero ON producto (idgenero);
CREATE INDEX idx_producto_idsubsub ON producto (idsubsub);

CREATE TABLE carrito (
    idcarrito integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcliente integer,
    idproducto integer,
    cantidad integer,
    preciounitario decimal(10,2),
    talla varchar(10),
    CONSTRAINT carrito_producto_fk FOREIGN KEY (idproducto) REFERENCES producto (idproducto) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT carrito_cliente_fk FOREIGN KEY (idcliente) REFERENCES cliente (idcliente) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_carrito_idproducto ON carrito (idproducto);
CREATE INDEX idx_carrito_idcliente ON carrito (idcliente);

CREATE TABLE favorito (
    idfavorito integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idproducto integer,
    idcliente integer,
    CONSTRAINT favorito_producto_fk FOREIGN KEY (idproducto) REFERENCES producto (idproducto) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT favorito_cliente_fk FOREIGN KEY (idcliente) REFERENCES cliente (idcliente) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_favorito_idproducto ON favorito (idproducto);
CREATE INDEX idx_favorito_idcliente ON favorito (idcliente);

CREATE TABLE pedido (
    idpedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcliente integer,
    fecha date,
    total decimal(10,2),
    CONSTRAINT pedido_cliente_fk FOREIGN KEY (idcliente) REFERENCES cliente (idcliente) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_pedido_idcliente ON pedido (idcliente);

CREATE TABLE sesion (
    idsesion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcliente integer,
    CONSTRAINT sesion_cliente_fk FOREIGN KEY (idcliente) REFERENCES cliente (idcliente) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_sesion_idcliente ON sesion (idcliente);
