CREATE TABLE pedido_detalle (
    iddetalle bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idpedido bigint NOT NULL,
    idproducto integer NOT NULL,
    talla varchar(10) NOT NULL,
    cantidad integer NOT NULL CHECK (cantidad > 0),
    precio_unitario decimal(10,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal decimal(12,2) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT pedido_detalle_pedido_fk FOREIGN KEY (idpedido) REFERENCES pedido (idpedido),
    CONSTRAINT pedido_detalle_producto_fk FOREIGN KEY (idproducto) REFERENCES producto (idproducto)
);

CREATE INDEX idx_pedido_detalle_idpedido ON pedido_detalle (idpedido);
CREATE INDEX idx_pedido_detalle_idproducto ON pedido_detalle (idproducto);
